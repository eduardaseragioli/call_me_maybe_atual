from pydantic import BaseModel
from typing import Any


class TypeInfo(BaseModel):
    """Represents the schema type information
                       for parameters or return values."""
    type: str
    items: "TypeInfo | None" = None
    properties: "dict[str, TypeInfo] | None" = None


class FunctionDefinition(BaseModel):
    """Defines a callable function, its
                    description, parameters, and return type."""
    name: str
    description: str
    parameters: dict[str, TypeInfo]
    returns: TypeInfo


class TestCase(BaseModel):
    """Represents an individual test case
                    containing a natural language prompt."""
    prompt: str


class FunctionCallResult(BaseModel):
    """Stores the structured result of a
                  function call generated by the decoder."""
    prompt: str
    name: str
    parameters: dict[str, Any]


class DecoderSettings(BaseModel):
    """Configuration settings for the
                 constrained decoder execution."""
    verbose: bool = False
    model_name: str = "Qwen/Qwen3-0.6B"
